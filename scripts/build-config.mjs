#!/usr/bin/env node
// Writes web/assets/config.js from public (non-secret) environment variables at deploy time.
import { writeFileSync } from 'node:fs';

const env = process.env;
const url = env.PUBLIC_CHECKOUT_URL || '';
if (url && !/^https:\/\/([a-z0-9-]+\.)*polar\.sh\//.test(url)) {
  console.error('PUBLIC_CHECKOUT_URL must be a polar.sh checkout link'); process.exit(1);
}
const cfg = {
  checkoutUrl: url,
  priceLabel: env.PUBLIC_PRICE_LABEL || '$5',
  analytics: { umamiWebsiteId: env.PUBLIC_UMAMI_WEBSITE_ID || '', umamiSrc: env.PUBLIC_UMAMI_SRC || '' },
};
writeFileSync(new URL('../web/assets/config.js', import.meta.url),
  `// Generated by scripts/build-config.mjs at deploy time. Safe to publish: no secrets here.\nexport default ${JSON.stringify(cfg, null, 2)};\n`);
console.log('config written', { checkout: Boolean(cfg.checkoutUrl), analytics: Boolean(cfg.analytics.umamiWebsiteId) });
